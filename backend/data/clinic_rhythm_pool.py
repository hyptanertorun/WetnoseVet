def get_pool_content_for_date(date_str: str) -> dict:
    """
    Belirli bir tarih için havuzdan içerik seç.
    Tarih bazlı deterministik seçim yapar (aynı tarihte aynı içerik).
    """
    import hashlib
    
    # Tarih string'inden hash oluştur
    date_hash = int(hashlib.md5(date_str.encode()).hexdigest(), 16)
    
    # Soru ve alarm için farklı indeksler seç
    question_index = date_hash % len(FEATURED_QUESTIONS_POOL)
    alarm_index = (date_hash // len(FEATURED_QUESTIONS_POOL)) % len(FALSE_ALARMS_POOL)
    
    return {
        "featured_question": FEATURED_QUESTIONS_POOL[question_index],
        "false_alarm": FALSE_ALARMS_POOL[alarm_index]
    }
